/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* Read the reset cause first. The RCC reset flags are sticky across resets
   * and are only cleared by software, so they must be sampled before any
   * other code has a chance to touch them - and then cleared, or every
   * subsequent boot would look like a watchdog reset. */
  s_reset_by_watchdog = WatchdogDriver_WasResetByWatchdog();
  WatchdogDriver_ClearResetFlags();

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  /* USER CODE BEGIN 2 */

  /* Deliberately empty. The ECU is brought up in the "USER CODE BEGIN BSP"
   * section below instead, because the BSP_LED_Init() and BSP_PB_Init() calls
   * that CubeMX places between here and there reconfigure PA5 and PC13 and
   * would overwrite our own pin configuration. Initialising after them means
   * our configuration is the one that survives. */

  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* USER CODE BEGIN BSP */

  /* ------------------------------------------------------------------------
   * ECU start-up
   *
   * Everything below replaces the CubeMX board-demo code. It runs here, after
   * the BSP has finished touching PA5 and PC13, so that the pin configuration
   * installed by our own drivers is the one that takes effect.
   * --------------------------------------------------------------------- */

  (void)BodyControl_Init();

  Logger_PrintBanner(s_reset_by_watchdog);

  if (!BodyControl_IsHealthy())
  {
      LOG_WARN("One or more subsystems failed to initialise - running degraded");
  }

  /* The watchdog is armed LAST, once every subsystem is up. Arming it earlier
   * would let a slow initialisation trigger a reset and leave the ECU in a
   * boot loop that looks exactly like a firmware hang.
   *
   * From this point the main loop must refresh it within the timeout or the
   * MCU resets. That is the intended contract, not a hazard. */
  if (!WatchdogDriver_Init())
  {
      LOG_ERROR("Watchdog failed to start - no hang protection active");
  }

  /* USER CODE END BSP */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      /* ------------------------------------------------------------------
       * The entire ECU runs from these two lines.
       *
       * Scheduler_Run() executes whichever registered tasks have come due
       * and returns immediately when none have. There is no delay here: the
       * loop spins freely, which is what keeps activation jitter down to the
       * duration of a single task rather than the length of a delay.
       *
       * WatchdogDriver_Refresh() is deliberately placed AFTER the scheduler,
       * and deliberately nowhere else. If any task hangs, the scheduler never
       * returns, the refresh never happens, and the watchdog resets the ECU -
       * which is precisely the behaviour we want.
       *
       * Refreshing from a timer interrupt instead would keep petting the
       * watchdog even while the main loop was dead, defeating the entire
       * mechanism. That mistake is common enough to be worth naming here.
       * ------------------------------------------------------------------ */

      Scheduler_Run();

      WatchdogDriver_Refresh();

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

